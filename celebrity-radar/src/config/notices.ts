/**
 * 平台公告（消息中心的「系统」一类）。
 *
 * 为什么是静态清单而不是一张集合：消息中心另外两类消息（关注更新、周报提醒）都能从
 * 端上已有数据算出来，只有「平台要说的话」没有数据源。写成常量最省事 —— 发布即上线，
 * 不必等一张新表加一次人工权限配置，也少一处后台维护入口。
 *
 * 维护约定：
 * 1. 新公告加在数组**头部**（列表按时间倒序，同日按数组顺序稳定排）；
 * 2. 历史条目的 `date` 不要改 —— 本机已读基线是时间戳，改旧日期会让它重新变成未读；
 * 3. 只放「说明性质」的内容（功能上线、口径说明、隐私与合规），不放营销与运营活动。
 */
export interface NoticeItem {
  id: string
  /** 发布日（YYYY-MM-DD）：消息中心据此排序并判断未读 */
  date: string
  title: string
  body: string
}

