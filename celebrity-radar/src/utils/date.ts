import dayjs from 'dayjs'

/**
 * 报告日期归一（单一出处）。
 *
 * 为什么要有这个文件：热度趋势（utils/trend.ts）与时间分布（utils/stats.ts，主页「时间分布」、
 * 周报「逐日分布」）都在做同一件事 —— 把模型给的日期字符串变成一个可比较的 Dayjs，
 * 再决定它落进哪个桶。两家一旦各写各的，就会出现「同一份报告，折线里进得去、柱状图里进不去」
 * 这种最难解释的现象（用户看到的是「图没了」，根因是两份正则不一致）。
 * 故解析规则收敛到这里，两个调用方只保留各自的**窗口与未来值策略**（那部分确实不同：
 * 趋势允许窗口内的未来日期，时间分布一律丢弃未来）。注意本文件只在 src/ 内复用；
 * 云函数是独立打包的，跨目录 require 部署后必然失效（同 llm.config.js 的说明）。
 *
 * 认哪些写法：**年月日齐全且无歧义**的形态 ——
 *   - `2026-10-08`、`2026/10/8`、`2026.10.08`
 *   - `2026年10月8日`（含不写「日」）
 *   - 带时间的 ISO（`2026-10-08T10:00:00.000Z`，取日期部分）
 *
 * 不认哪些：只到月份的 `2026-09`（得替它补日）、只有月日的 `9月8日`（得替它猜年）。
 * 这类属于「猜」，宁可少一个点 —— 与报告里其它「不确定就不呈现」的取舍一致。
 *
 * 起因：模型偶尔把 date 写成 `2026年9月30日`，而早先的 `^\d{4}-\d{2}-\d{2}` 只认短横线，
 * 那一天的所有条目会被静默丢弃 —— 表现就是「有的条目在图上、同一天的另一些不在」。
 */
const DAY_SHAPES = [
  /^(\d{4})[-/.](\d{1,2})[-/.](\d{1,2})/,
  /^(\d{4})\s*年\s*(\d{1,2})\s*月\s*(\d{1,2})\s*日?/
]

/**
 * 解析日期；不可解析返回 null（调用方一律「忽略这一条」，不要回落成今天）。
 * 合法性与 dayjs 一致（`2026-02-31` 会被 JS Date 顺势滚成 3 月 3 日，与改动前行为相同）。
 */
export function parseDay(raw: string | undefined): dayjs.Dayjs | null {
  const s = (raw ?? '').trim()
  if (s === '') return null
  for (const re of DAY_SHAPES) {
    const m = re.exec(s)
    if (!m) continue
    const d = dayjs(
      `${m[1]}-${String(m[2]).padStart(2, '0')}-${String(m[3]).padStart(2, '0')}`
    )
    return d.isValid() ? d : null
  }
  return null
}
